const buildKnowledgeDepthInstructions = (knowledgeDepth: KnowledgeDepth) => {
  const profile = KNOWLEDGE_DEPTH_PROFILES[knowledgeDepth];
  return `・テーマへの詳しさ: ${profile.label}。
・英語レベルとテーマへの詳しさは別軸である。英語レベルは「英文の語彙・文法・構文の難しさ」、テーマへの詳しさは「扱う情報・論点の深さ」を決める。詳しい読者向けだからといって、指定英語レベルを超える難語でごまかさない。
${profile.contentRules.map(rule => `・${rule}`).join('\n')}`;
};

const buildMnemonicRules = () => `【覚え方のルール】
・英単語の主要な音を、元の順番をできるだけ保ちながら日本語の空耳に変換する。
・「音が似ている」だけで終わらず、ありえない・意外・シュールなど、具体的な映像が浮かぶ1文にする。
・文末またはオチに、その単語の日本語の意味を【 】で入れ、音と意味を直接結びつける。
・多少の強引さは許容するが、元の発音との対応が弱い語呂は採用しない。
・性的、差別的、特定個人を侮辱する内容、過度に残虐な内容は避ける。
・形式は「空耳を使った短い文【日本語の意味】」の1行だけにする。
良い例: Specific → スペース引くほど【具体的】に
良い例: Struggle → 素手で虎来る、必死に【もがく】
良い例: Ambiguous → 案、微妙で具体性なく【曖昧】っす`;

const buildPersonalInstructions = (inspirationSeed?: string, angerSeed?: string) => {
  const blocks: string[] = [];
  if (inspirationSeed?.trim()) {
    blocks.push(`【ひらめきの種】\n以下はユーザーの好きなことや近況です。英文の題材、解説、例文に、学習内容を邪魔しない範囲で自然に活用してください。\n${inspirationSeed.trim()}`);
  }
  if (angerSeed?.trim()) {
    blocks.push(`【怒りの種】\n以下はユーザーが嫌いなこと・避けたいことです。解説キャラクターの口調に合う場合だけ、事実を捏造せず、軽い皮肉やツッコミとして自然に活用してください。\n${angerSeed.trim()}`);
  }
  return blocks.length ? `\n\n${blocks.join('\n\n')}` : '';
};

export const buildReadingPrompt = ({
  topic,
  additionalRequest = '',
  level,
  knowledgeDepth = 'familiar',
  length,
  role,
  trait,
  inspirationSeed = '',
  angerSeed = '',
}: ReadingPromptConfig) => {
  const topicText = topic.trim() || '日本のラーメン文化';
  const requestText = additionalRequest.trim();
  const readerRole = getReaderCompatibleRole(role);
  const personaName = '（役割と性格にふさわしい日本の下の名前またはあだ名を1つだけ決める）';
  const depthProfile = KNOWLEDGE_DEPTH_PROFILES[knowledgeDepth];
  const extraRequest = requestText
    ? `\n【追加要望】\n${requestText}\nこの追加要望は、英文の内容・使う語・例文・解説に、自然で教育的な範囲で反映してください。無理に毎回入れないでください。`
    : '';
  const personalInstructions = buildPersonalInstructions(inspirationSeed, angerSeed);

  return `あなたはREADON用の英語長文教材を作る編集者兼英語講師です。
テーマは「${topicText}」です。英文の難易度は指定された英語レベルだけを基準に調整し、扱う情報・論点の深さは指定された「テーマへの詳しさ」に合わせてください。日本語の訳と解説は、その英語レベルの学習者が理解しやすい表現にしてください。${extraRequest}${personalInstructions}

【最優先：アプリが正しく解析するための機械的ルール】
・最終回答は、教材データだけを出力する。挨拶、前置き、あとがき、Markdownコードフェンスは付けない。
・区切り行「----------」は、全出力中に独立した1行として厳密に2回だけ使う。英文、解説、JSON文字列、例文、背景知識の中では使わない。
・最初の区切り行より前は、【解説担当】プロフィールと「英文1行→日本語訳1行→解説1行」の3行セットだけにする。
・英文1行には英文を1文だけ置き、漢字・ひらがな・カタカナなどの日本語文字を混ぜない。日本語の固有語も必要ならローマ字で書く。
・日本語訳と解説は、それぞれ物理的に1行で完結させ、途中改行しない。
・各文の間に番号、段落名、見出し、箇条書き、注釈を入れない。
・同じ英文全文を別の場所に再掲しない。

【出力形式】
【解説担当】
名前: ${personaName}
役割: ${readerRole}
性格: ${trait}

[英語の原文一文]
[その一文だけの自然な日本語訳]
[解説] （AIが決めた名前）（${readerRole}）: [解説コメント]

[次の英語の原文一文]
[その一文だけの自然な日本語訳]
[解説] （AIが決めた名前）（${readerRole}）: [解説コメント]

（全文の文数だけ同じ3行セットを繰り返す）
----------
[
  {
    "front": "ramen",
    "back": "ラーメン、中華麺",
    "pronunciation": "[ラ]ーメン",
    "memo": "【語源・雑学】短く正確な情報。\\n【覚え方】音と意味を結ぶ短い覚え方。\\n【例文】対象語を使った自然で少し面白い英文。"
  }
]
----------
[背景知識を日本語で約400文字]

【英文の内容・難易度】
・英語レベル: ${level}。必ずこのレベルを守り、特に語彙だけを不必要に難しくしない。
${buildKnowledgeDepthInstructions(knowledgeDepth)}
・長さ: 約${length}語。
・論理構成: 4段落相当。導入→具体化→別角度または対比→まとめ、を基本にする。ただし、アプリ解析のため段落番号や段落見出しは出力しない。
・具体例を使い、一面的な礼賛や批判にせず、読み物として内容のあるバランスの取れた英文にする。
・事実、歴史、語源、統計、固有名詞を作り話で補わない。確信できない細部は断定せず、本文の主張に不要なら省く。
・独創性は、比喩、語呂、例文、キャラクターのリアクションに使い、事実の創作には使わない。

【対訳・解説】
・英文と日本語訳は必ず1対1で対応させる。訳に次の文の情報を先取りしない。
・プロフィールで名前を1回だけ決め、その名前と役割を全ての[解説]行で一字一句変えない。
・各解説は原則70〜130字程度、複雑な文でも150字程度までを目安にする。
・解説は、①実際の英単語を使った主節の構造（必要ならS/V/O/C）、②重要語句または文法ポイント1つ、③内容理解を助ける短い説明またはキャラクターらしい反応、を基本にする。
・毎文に雑学を詰め込まない。雑学は、その文の理解に直接役立ち、確実性が高い場合だけ短く入れる。
・「命名した」「名前:」など、人物名ではない文字列を話者名に付けない。

【単語JSON】
・最初の区切り行と2つ目の区切り行の間には、有効なJSON配列だけを置く。
・配列要素は厳密に30件。同じfrontを重複させず、単純な複数形や派生形だけで水増ししない。
・各要素のキーは "front", "back", "pronunciation", "memo" の4つだけ。全て文字列にする。
・frontは、本文の英文行に実際に登場した綴りを使う。英単語だけにし、絵文字、発音、品詞記号を混ぜない。
・backは本文中での意味を最初に置き、主要な意味を合計1〜3個にする。数合わせのため不自然な意味を足さない。
・pronunciationは一般的なカタカナ発音にし、最も強く読む部分を半角[ ]で1か所囲む。
・memoは必ず「【語源・雑学】→【覚え方】→【例文】」の順で、各見出しを1回だけ使う。3項目を1つの文字列にし、項目間の改行はJSON文字列内の \\n で表現する。
・【語源・雑学】は1〜2文程度。語源、同語源語、文化・歴史・科学の雑学のうち、信頼性が高く学習に役立つものだけを書く。不確かな語源説を断定しない。
・【覚え方】は1文だけにする。
${buildMnemonicRules()}
・【例文】は対象語を必ず使った自然な英語1文にする。少し笑える・意外な内容は歓迎する。追加要望やパーソナル設定は、自然に合う場合だけ活用する。
・JSONではダブルクォートを使い、末尾カンマ、コメント、Markdown、JSON前後の説明文を入れない。文字列内でダブルクォートが必要なら正しくエスケープする。

【背景知識】
・2つ目の区切り行の後に、この長文をより深く理解するための背景知識・関連情報・うんちくを日本語で約400文字書く。
・${depthProfile.backgroundRule}
・本文の言い換えだけにせず、選択された「テーマへの詳しさ」より一歩理解が広がる補足を優先する。
・事実確認に自信がない固有名詞・年号・数値は無理に入れない。
・Markdownの強調記法は使わず、プレーンテキストにする。

【出力前の内部検査】
最終回答を出す前に、以下を内部で確認してください。検査結果や説明は出力しないでください。問題があれば内部で修正し、完成データだけを出してください。
1. 区切り行「----------」が厳密に2回だけか。
2. 全英文が「英文1行→訳1行→解説1行」の3行単位になっているか。
3. 各英文行が1文だけで、日本語文字を含んでいないか。
4. 全英文に対応する訳と解説が1つずつあるか。
5. 解説者の名前と役割がプロフィールと全行で完全一致しているか。
6. 解説が途中改行されていないか。
7. 単語部分が構文上有効なJSON配列か。
8. JSONが厳密に30件で、各要素のキーが4つだけか。
9. frontの重複がなく、全frontが本文の英文行に実際に登場しているか。
10. memoの3見出しが各1回、正しい順番か。
11. JSON文字列内の改行・引用符が正しくエスケープされているか。
12. JSONやmemoの中に「----------」が紛れ込んでいないか。
13. 背景知識がJSONの外、2つ目の区切り行の後だけにあるか。
14. 余計な挨拶、前置き、コードフェンス、英文全文の重複がないか。
15. 選択された「テーマへの詳しさ」に内容が合っているか。初心者なのに前提知識を要求していないか。専門家級なのに一般的な入門説明ばかりになっていないか。内容の深さを英語語彙の難しさだけで表現していないか。`;
};
